#!/system/bin/sh
# log.sh — диагностический лог модуля. Подключается через `.` из post-fs-data.sh,
# service.sh и storage.sh.
#
# Диагностическая сборка пишет лог ПО УМОЛЧАНИЮ. Отключается файлом-маркером
# /data/adb/unfuse_zygisk.nolog — он и есть «стоп»: положил файл, перезагрузился,
# модуль снова молчит и отчитывается только кодом возврата (правило проекта).
#
# Почему по умолчанию пишем, а не наоборот: сборка собирается ровно за тем,
# чтобы получить лог с устройства пользователя, куда у нас нет доступа. Включение
# «через маркер» требовало от пользователя лишнего шага, который он не знает, —
# лог не появлялся, и разбор не начинался. Проверка маркера — одноразовая, в
# известной точке (начало post-fs-data и начало service), а не сторож: модуль не
# заводит процессов, которые наблюдают за системой.
#
# Отключить:
#   touch /data/adb/unfuse_zygisk.nolog   # затем перезагрузить устройство
# Включить обратно:
#   rm /data/adb/unfuse_zygisk.nolog
# Снять снимок руками, без перезагрузки:
#   sh /data/adb/modules/unfuse_zygisk/diag.sh [--probe <пакет>]
#
# Имя лога — .debug.log, а НЕ unfuse_zygisk.log: последний занят. На `marble`
# там лежат 121 КБ от снятого механизма marble_unfuse_auto (sdcardfs на
# /mnt/runtime/*/emulated, /data/adb/marble_unfuse_auto.conf). Автозапуска у
# него уже нет — файл мёртвый, но дописываться в чужой лог модуль не должен,
# и удалять чужие данные он тоже не должен.

UNFUSE_NOLOG=${UNFUSE_NOLOG:-/data/adb/unfuse_zygisk.nolog}
UNFUSE_LOG=${UNFUSE_LOG:-/data/adb/unfuse_zygisk.debug.log}
# Логирование включено? Единственная точка решения — отсутствие файла-«стоп».
unfuse_logging() { [ ! -f "$UNFUSE_NOLOG" ]; }

# unfuse_log_begin — вызывается один раз за загрузку, в самом её начале
# (post-fs-data.sh). Файл лога перезаписывается ЦЕЛИКОМ и БЕЗУСЛОВНО: в нём
# всегда только текущая загрузка, история прошлых не накапливается.
#
# Так было не всегда. Раньше обрезку сторожил опорный идентификатор загрузки
# (boot_id) и файл-метка $MODDIR/.log_boot рядом с модулем — механизм обрезал
# файл «ровно один раз за загрузку». Он убран целиком: безусловной обрезки
# достаточно, а состояние на диске и разбор «чей это запуск» были лишними.
#
# Единственная точка обрезки — начало загрузки. service.sh НЕ обрезает: он
# дописывает свою стадию в файл этой же загрузки, и обрезка стёрла бы снимок
# post-fs-data. Если post-fs-data в загрузке не отработал, обрезать лог некому —
# но тогда модуль не сделал и своей работы, и лог тут ни при чём.
unfuse_log_begin() {
    unfuse_logging || return 0
    : >"$UNFUSE_LOG"
    return 0
}

# log <текст...>
log() {
    unfuse_logging || return 0
    printf '%s %s\n' "$(date '+%m-%d %H:%M:%S')" "$*" >>"$UNFUSE_LOG" 2>/dev/null
    return 0
}

# run_logged <подпись> <команда...> — выполняет команду и записывает её код
# возврата. Вывод команды тоже уходит в лог: инструменты молчат, но --dump и
# --probe говорят, и именно их вывод нужен при разборе.
run_logged() {
    if ! unfuse_logging; then
        shift
        "$@"
        return $?
    fi

    _tag=$1
    shift
    _t0=$(date '+%m-%d %H:%M:%S')
    "$@" >>"$UNFUSE_LOG" 2>&1
    _rc=$?
    printf '%s %s: rc=%s\n' "$_t0" "$_tag" "$_rc" >>"$UNFUSE_LOG" 2>/dev/null
    return $_rc
}

# unfuse_diag <MODDIR> [стадия] — снимок состояния в лог. Всегда ПОЛНЫЙ: лог просто
# перезаписывается текущим состоянием, никаких сравнений с прошлым прогоном.
unfuse_diag() {
    unfuse_logging || return 0
    _dir=$1
    _stage=${2:-}
    UNFUSE_STAGE=$_stage sh "$_dir/diag.sh" --log >/dev/null 2>&1
    return 0
}
