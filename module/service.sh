#!/system/bin/sh
#
# service.sh — повтор подготовки после того, как vold смонтирует хранилища.
#
# vold при подготовке /data/media мог вернуть ярлык media_userdir_file, поэтому
# оба шага storage.sh повторяются уже после его старта. Шаги идемпотентны.
#

MODDIR=${MODDIR:-${0%/*}}
LOG=/data/adb/sdcardfs_restore.log

sh "$MODDIR/storage.sh" service

# --- поздний повтор: закрыть гонку с vold -------------------------------------
#
# service.sh выполняется на стадии late_start, но vold готовит /data/media/0 и
# ПОЗЖЕ — при монтировании хранилища и при разблокировке пользователя. Его
# подготовка заканчивается вызовом SetDefaultAcl, а тот ставит на /data/media/0
# default-ACL с ИМЕНОВАННОЙ записью для группы 1023 (media_rw), перекрывая то,
# что выставил storage.sh. Проверено на устройстве: после загрузки у
# /data/media/0 access-ACL содержит GROUP(9997), а default-ACL — GROUP(1023),
# тогда как у всех остальных каталогов в обоих ACL стоит 9997.
#
# Чем это плохо. Доступ к общему хранилищу выдаёт именно именованная запись для
# 9997. Каталог, созданный в /data/media/0 процессом, на который хуки libc не
# распространяются (vold, MTP, root-демон), наследует default-ACL родителя — то
# есть запись для 1023, а не для 9997, и приложения его не увидят. Файлы,
# созданные самими приложениями, хук правит сам, поэтому дыра узкая, но она есть.
#
# Убрать гонку на стороне vold, не патча его, нельзя. Зато шаг 3 идемпотентен, и
# его можно повторить, когда система действительно догрузилась. Точный момент,
# когда vold ставит свой default-ACL в последний раз, неизвестен (это зависит от
# разблокировки и монтирования хранилища), поэтому повтор не один: три прохода с
# растущими паузами. Стоит это около секунды процессорного времени на проход, а
# закрывает и случай, когда vold дорабатывает уже после boot_completed.
#
# Повтор идёт фоном: service.sh обязан вернуться сразу, иначе init заблокируется
# на нём (проверено — возврат за 0 с).
(
    i=0
    while [ "$(getprop sys.boot_completed 2>/dev/null)" != "1" ] && [ "$i" -lt 120 ]; do
        sleep 2
        i=$((i + 1))
    done

    # boot_completed выставляется до того, как vold закончит с хранилищем,
    # поэтому даём ему устояться, и только потом правим ACL.
    for pause in 15 30 75; do
        sleep "$pause"
        echo "[$(date '+%Y-%m-%d %H:%M:%S')] late: повтор ACL (пауза ${pause}с)" >> "$LOG"
        sh "$MODDIR/storage.sh" late >> "$LOG" 2>&1
    done
) &
