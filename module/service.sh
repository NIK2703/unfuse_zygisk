#!/system/bin/sh
#
# service.sh — повтор подготовки после того, как vold смонтирует хранилища.
#
# vold при подготовке /data/media мог вернуть ярлык media_userdir_file, поэтому
# оба шага storage.sh повторяются уже после его старта. Шаги идемпотентны.
#

MODDIR=${MODDIR:-${0%/*}}
LOG=/data/adb/sdcardfs_restore.log
stamp() { date '+%Y-%m-%d %H:%M:%S'; }

sh "$MODDIR/storage.sh" service

# --- снять с vold запись default-ACL для группы 1023 --------------------------
#
# Повтор: патч живёт только в памяти процесса, а на стадии post-fs-data vold мог
# ещё не существовать. Шаг идемпотентен, поэтому повтор ничего не стоит.
NOACL="$MODDIR/tools/vold-noacl"
NOACL_OK=0
if [ -x "$NOACL" ] && "$NOACL" >>"$LOG" 2>&1; then
    NOACL_OK=1
fi

if [ "$NOACL_OK" = "1" ]; then
    # Патч стоит: vold больше не переписывает default-ACL у /data/media/0, и
    # гонки, которую закрывали повторные проходы, просто нет.
    echo "[$(stamp)] service: патч vold на месте — повторные проходы ACL не нужны" >>"$LOG"
    exit 0
fi

# --- запасной путь: повторные проходы ACL -------------------------------------
#
# Сюда попадаем, если vold оказался другой сборки и утилита отказалась патчить
# (код 2), либо если утилиты нет. Тогда остаётся прежний способ — закрывать
# гонку повторами.
#
# vold готовит /data/media/0 не только на этой стадии, но и позже: при
# монтировании хранилища и при разблокировке пользователя. Его подготовка
# заканчивается вызовом SetDefaultAcl, а тот ставит на /data/media/0 default-ACL
# с ИМЕНОВАННОЙ записью для группы 1023 (media_rw), перекрывая то, что выставил
# storage.sh. Проверено на устройстве: после загрузки у /data/media/0 access-ACL
# содержит GROUP(9997), а default-ACL — GROUP(1023), тогда как у всех остальных
# каталогов в обоих ACL стоит 9997.
#
# Чем это плохо. Доступ к общему хранилищу выдаёт именно именованная запись для
# 9997. Каталог, созданный в /data/media/0 процессом, на который хуки libc не
# распространяются (vold, MTP, root-демон), наследует default-ACL родителя — то
# есть запись для 1023, а не для 9997, и приложения его не увидят. Файлы,
# созданные самими приложениями, хук правит сам, поэтому дыра узкая, но она есть.
#
# Точный момент, когда vold ставит свой default-ACL в последний раз, неизвестен
# (это зависит от разблокировки и монтирования хранилища), поэтому повтор не
# один: три прохода с растущими паузами. Стоит это около секунды процессорного
# времени на проход, а закрывает и случай, когда vold дорабатывает уже после
# boot_completed.
#
# Повтор идёт фоном: service.sh обязан вернуться сразу, иначе init заблокируется
# на нём (проверено — возврат за 0 с).
echo "[$(stamp)] service: патч vold НЕ встал — включаю повторные проходы ACL" >>"$LOG"
(
    i=0
    while [ "$(getprop sys.boot_completed 2>/dev/null)" != "1" ] && [ "$i" -lt 120 ]; do
        sleep 2
        i=$((i + 1))
    done

    # boot_completed выставляется до того, как vold закончит с хранилищем,
    # поэтому даём ему устояться, и только потом правим ACL.
    for pause in 15 30 75; do
        sleep "$pause"
        echo "[$(stamp)] late: повтор ACL (пауза ${pause}с)" >> "$LOG"
        sh "$MODDIR/storage.sh" late >> "$LOG" 2>&1
    done
) &
