#!/system/bin/sh
# vold-targets.sh — применимость ОБОИХ vold-хуков к КАЖДОМУ целевому образу vold.
#
# Зачем. Для libc применимость по образу проверяет tools/verify-hook-targets.py,
# а для vold не проверял никто: --selftest не вызывался ни одним прогоном, а
# применимость к файлу смотрели руками. Между тем обе программы умеют ответить
# на ФАЙЛЕ, ничего в него не записывая (ветка --file возвращается раньше записи):
#
#   vold-noacl  --file <vold> --selftest   .rela.plt <-> .plt взаимно однозначно
#                                          по ВСЕМ символам образа
#   vold-noacl  --file <vold> --dry-run    setxattr разрешается, трамплин цел
#   vold-fusefs --file <vold> --dry-run    mount и umount2 разрешаются, ОБА
#                                          трамплина целы, и структурно найден
#                                          ровно один вызов mount("/dev/fuse",
#                                          ..., "fuse", ..., MS_LAZYTIME)
#
# Третья строка — не то же самое, что первые две, и это и есть применимость
# mount-хука: без единственной найденной площадки вызова обработчику нечем
# отличить MountUserFuse() от AppFuseUtil::Mount(), и vold-fusefs отказывается
# ставить патч (код 2) — см. find_fuse_site() и MS_LAZYTIME в tools/vold-fusefs.c.
#
# --selftest при успехе МОЛЧИТ (логгирование из инструментов убрано, результат —
# код возврата), поэтому печатаются коды, а не вывод.
#
# Четвёртая колонка — `vold-fusefs --file <vold> --room`: есть ли в ОБРАЗЕ место
# под обработчики (прогон нулей после последнего трамплина .plt). Это
# единственное звено цепочки, которое по файлу не проверялось, потому что --file
# возвращался раньше find_handler_room(). «Нет места» — не непригодность: патч
# тогда просит vold отобразить страницу собственного бинарника исполняемой
# (vold_exec_page, ptrace), и вот именно этот шаг и может быть отвергнут, так что
# знать ответ по релизам стоит. В вердикт колонка не входит.
#
# Использование: sh vold-targets.sh [каталог-образов [vold-noacl [vold-fusefs]]]
#   каталог по умолчанию /data/local/tmp/voldimg
#   инструменты по умолчанию /data/local/tmp/vold-{noacl,fusefs}-test
# Код возврата: 0 все образы пригодны; 1 есть непригодный; 2 нечего проверять.

DIR="${1:-/data/local/tmp/voldimg}"
N="${2:-/data/local/tmp/vold-noacl-test}"
F="${3:-/data/local/tmp/vold-fusefs-test}"

[ -d "$DIR" ] || { echo "нет каталога $DIR" >&2; exit 2; }
[ -x "$N" ]   || { echo "нет инструмента $N" >&2; exit 2; }
[ -x "$F" ]   || { echo "нет инструмента $F" >&2; exit 2; }

# 0 на месте/ок, 1 трамплин цел, 2 не разобрать, 3 не записать, 4 нет файла.
# 5..10 — это НЕ «вообще не разобрать», а конкретная причина, по которой не
# разрешился якорь (см. usage vold-fusefs): именно так выглядел бы провал на
# релизе с изменившейся формой, и код говорит, какая форма изменилась.
word() {
    case "$1" in
        0) echo ok ;;
        1) echo "трамплин-цел" ;;
        2) echo "НЕ-РАЗОБРАТЬ" ;;
        3) echo "НЕ-ЗАПИСАТЬ" ;;
        4) echo "НЕТ-ФАЙЛА" ;;
        5) echo "нет-\"/dev/fuse\"" ;;
        6) echo "нет-\"fuse\"" ;;
        7) echo "строк-не-одна" ;;
        8) echo "нет-площадки" ;;
        9) echo "нет-LAZYTIME" ;;
        10) echo "LAZYTIME>1" ;;
        # 11..16 возможны только на живом процессе: места в образе нет ни на
        # одной версии, поэтому обработчики всегда кладутся в страницу, которую
        # vold отображает из собственного бинарника. Именно этот шаг и может
        # отказать на ужесточённой версии, поэтому у каждого отказа свой код.
        11) echo "нет-ptrace" ;;
        12) echo "нет-страницы" ;;
        13) echo "не-записать-путь" ;;
        14) echo "не-открыть-vold" ;;
        15) echo "не-отобразить" ;;
        16) echo "не-знаем-путь" ;;
        17) echo "БЕЗ-ПРИЧИНЫ" ;;
        # 18 — площадок-кандидатов больше, чем влезает в список: единственность
        # недоказуема. По файлу недостижимо (в vold их ровно две), но код есть,
        # и он не должен печататься как «код-18».
        18) echo "площадок>8" ;;
        19) echo "ошибка-аргументов" ;;
        *) echo "код-$1" ;;
    esac
}

# --room: 0 в образе, 1 нет (нужна страница через ptrace), 2 не разрешилось
roomword() {
    case "$1" in
        0) echo "в образе" ;;
        1) echo "нет" ;;
        2) echo "НЕ-РАЗОБРАТЬ" ;;
        *) echo "код-$1" ;;
    esac
}

printf '%-16s %-13s %-15s %-9s %-9s %s\n' \
       "образ" "setxattr" "mount+umount2" "selftest" "место" "вердикт"
echo "---------------------------------------------------------------------------"
echo

n=0
bad=0
for f in "$DIR"/*; do
    [ -f "$f" ] || continue
    name="${f##*/}"

    "$N" --file "$f" --dry-run  >/dev/null 2>&1; rs=$?
    "$F" --file "$f" --dry-run  >/dev/null 2>&1; rf=$?
    "$N" --file "$f" --selftest >/dev/null 2>&1; ss=$?
    "$F" --file "$f" --room     >/dev/null 2>&1; rm=$?

    n=$((n + 1))
    if [ "$rs" = 0 ] && [ "$rf" = 0 ] && [ "$ss" = 0 ]; then
        v="пригоден"
    else
        v="НЕПРИГОДЕН"
        bad=$((bad + 1))
    fi
    printf '%-16s %-13s %-15s %-9s %-9s %s\n' \
           "$name" "$(word $rs)" "$(word $rf)" "$(word $ss)" \
           "$(roomword $rm)" "$v"
done

if [ "$n" = 0 ]; then
    echo "в $DIR нет файлов" >&2
    exit 2
fi

echo
echo "образов: $n, непригодных: $bad"
[ "$bad" = 0 ] || exit 1
